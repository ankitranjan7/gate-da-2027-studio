export function getModuleMetaById(id: string): StudyModuleMeta {
  return ALL_STUDY_MODULES.find((m) => m.id === id) ?? ALL_STUDY_MODULES[0]
}

export interface ModuleWithChapters {
  meta: StudyModuleMeta
  chapters: ChapterData[]
}

export async function loadAllModulesWithChapters(): Promise<ModuleWithChapters[]> {
  const results = await Promise.all(
    ALL_STUDY_MODULES.map(async (meta) => ({
      meta,
      chapters: await meta.loadChapters(),
    }))
  )
  return results
}
